# ============================================================
# Задача 2.2. Сумма цифр трёхзначного числа
# ============================================================
# Дано трёхзначное число. Найдите сумму его цифр, используя
# только арифметические операции.
#
# Пример:
#   In: 456
#   Out: 15 (4 + 5 + 6)
#
# Подсказка: n // 100, (n // 10) % 10, n % 10.

def sum_digits(n: int) -> int:
    return n // 100 + (n // 10) % 10 + n % 10
